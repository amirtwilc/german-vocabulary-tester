/** The editable vocabulary pool. Add or remove entries here, then redeploy. */
export type Article = 'der' | 'die' | 'das';
export type Auxiliary = 'hat' | 'ist';
export type VerbCase = 'Akkusativ' | 'Dativ' | 'Akkusativ + Dativ';
export type PresentPerson = 'ich' | 'du' | 'erSieEs' | 'wir' | 'ihr' | 'sieSie';
export type PrepositionCase = 'Akkusativ' | 'Dativ';
export type CanonicalPrepositionCategory =
  | 'Accusative'
  | 'Dative'
  | 'Accusative + Dative';

export interface Noun {
  id: string;
  german: string;
  english: string;
  /** Omit for nouns without a plural in the recorded meaning. */
  plural?: string;
  article: Article;
}

export interface Verb {
  id: string;
  infinitive: string;
  english: string;
  /** Optional German form shown only for the primary translation question. */
  translationGerman?: string;
  /** Optional second meaning question attached to the same grammatical verb. */
  alternateTranslation?: {
    german: string;
    english: string;
  };
  present?: Partial<Record<PresentPerson, string>>;
  /** Optional simple-past forms. Every provided person can become a written Präteritum question. */
  preterite?: Partial<Record<PresentPerson, string>>;
  pastParticiple?: string;
  auxiliary?: Auxiliary;
  case?: VerbCase;
  notes?: string;
}

export interface AdjectiveAdverb {
  id: string;
  kind: 'adjective' | 'adverb';
  german: string;
  english: string;
  comparative?: string;
  superlative?: string;
}

export type Preposition =
  | { id: string; german: string; usage: 'fixed'; case: PrepositionCase }
  | { id: string; german: string; usage: 'two-way' };

export const CANONICAL_PREPOSITION_GROUPS = [
  {
    category: 'Accusative',
    words: ['bis', 'durch', 'für', 'gegen', 'ohne', 'um'],
  },
  {
    category: 'Accusative + Dative',
    words: [
      'an',
      'auf',
      'hinter',
      'in',
      'neben',
      'über',
      'unter',
      'vor',
      'zwischen',
    ],
  },
  {
    category: 'Dative',
    words: [
      'ab',
      'aus',
      'außer',
      'bei',
      'gegenüber',
      'mit',
      'nach',
      'seit',
      'von',
      'zu',
    ],
  },
] as const satisfies readonly {
  category: CanonicalPrepositionCategory;
  words: readonly string[];
}[];

const canonicalId = (word: string) =>
  word
    .replace(/ä/g, 'ae')
    .replace(/ö/g, 'oe')
    .replace(/ü/g, 'ue')
    .replace(/ß/g, 'ss');

export const normalizeCanonicalPreposition = (word: string) =>
  word
    .trim()
    .toLocaleLowerCase('de-DE')
    .normalize('NFC')
    .replace(/ä/g, 'ae')
    .replace(/ö/g, 'oe')
    .replace(/ü/g, 'ue')
    .replace(/ß/g, 'ss');

export interface CanonicalPreposition {
  german: string;
  category: CanonicalPrepositionCategory;
}

export const CANONICAL_PREPOSITIONS: readonly Preposition[] =
  CANONICAL_PREPOSITION_GROUPS.flatMap(({ category, words }) =>
    words.map(
      (german): Preposition =>
        category === 'Accusative + Dative'
          ? { id: canonicalId(german), german, usage: 'two-way' }
          : {
              id: canonicalId(german),
              german,
              usage: 'fixed',
              case: category === 'Accusative' ? 'Akkusativ' : 'Dativ',
            },
    ),
  );

const canonicalPrepositionByNormalizedWord = new Map(
  CANONICAL_PREPOSITION_GROUPS.flatMap(({ category, words }) =>
    words.map(
      (german) =>
        [normalizeCanonicalPreposition(german), { german, category }] as const,
    ),
  ),
);

export const getCanonicalPreposition = (
  word: string,
): CanonicalPreposition | undefined =>
  canonicalPrepositionByNormalizedWord.get(normalizeCanonicalPreposition(word));

